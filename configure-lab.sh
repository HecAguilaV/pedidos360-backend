#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# Pedidos360 — AWS Learner Lab Rotation Helper (configure-lab.sh)
# Generates a complete .env file for a new disposable AWS Lab without code edits.
# Supports both interactive prompts and non-interactive environment overrides.
# ==============================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="${SCRIPT_DIR}/.env"

prompt_val() {
  local var_name="$1"
  local prompt_text="$2"
  local default_val="$3"
  local current_val="${!var_name:-}"

  if [[ -n "${NON_INTERACTIVE:-}" ]]; then
    echo "${current_val:-$default_val}"
    return
  fi

  local input=""
  read -r -p "${prompt_text} [${default_val}]: " input
  echo "${input:-$default_val}"
}

echo "=================================================================="
echo " Pedidos360 — Configuración Rápida de Laboratorio AWS (EC2 / RDS)"
echo "=================================================================="

SPRING_PROFILE=$(prompt_val "SPRING_PROFILES_ACTIVE" "1. Perfil de Spring (prod para AWS, dev para local)" "prod")
PUBLIC_ORIGIN=$(prompt_val "PUBLIC_ORIGIN" "2. URL pública HTTPS (CloudFront https://dxxx.cloudfront.net) o HTTP EC2" "http://localhost")
EC2_PUBLIC_IP=$(prompt_val "EC2_PUBLIC_IP" "3. IP pública de EC2 (opcional, para CORS adicional)" "")
DB_HOST_VAL=$(prompt_val "DB_HOST" "4. Host PostgreSQL (endpoint RDS o 'postgres' para contenedor local)" "postgres")
DB_PORT_VAL=$(prompt_val "DB_PORT" "5. Puerto PostgreSQL" "5432")
DB_NAME_VAL=$(prompt_val "DB_NAME" "6. Nombre de base de datos" "pedidos360")
DB_USER_VAL=$(prompt_val "DB_USERNAME" "7. Usuario PostgreSQL" "postgres")
DB_PASS_VAL=$(prompt_val "DB_PASSWORD" "8. Contraseña PostgreSQL" "postgres")
COGNITO_REGION_VAL=$(prompt_val "COGNITO_REGION" "9. Región AWS Cognito" "us-east-1")
COGNITO_POOL_VAL=$(prompt_val "COGNITO_USER_POOL_ID" "10. Cognito User Pool ID (ej. us-east-1_AbCdEf123)" "")
COGNITO_CLIENT_VAL=$(prompt_val "COGNITO_CLIENT_ID" "11. Cognito App Client ID" "")
COGNITO_DOMAIN_VAL=$(prompt_val "COGNITO_DOMAIN" "12. Cognito Hosted UI Domain (ej. https://p360.auth.us-east-1.amazoncognito.com)" "")
MAIL_USER_VAL=$(prompt_val "MAIL_USERNAME" "13. Correo Gmail SMTP (notifications-service)" "")
MAIL_PASS_VAL=$(prompt_val "MAIL_PASSWORD" "14. App Password Gmail SMTP (16 caracteres)" "")

PUBLIC_ORIGIN_CLEAN="${PUBLIC_ORIGIN%/}"
if [[ -n "${COGNITO_POOL_VAL}" ]]; then
  COGNITO_ISSUER_VAL="https://cognito-idp.${COGNITO_REGION_VAL}.amazonaws.com/${COGNITO_POOL_VAL}"
else
  COGNITO_ISSUER_VAL=""
fi

COGNITO_REDIRECT_VAL="${PUBLIC_ORIGIN_CLEAN}/login"

CORS_LIST="http://localhost:4200,http://localhost:80,http://localhost:8080,http://localhost,http://*:4200,http://*:80,http://*:8080,https://*.amazonaws.com,https://*.cloudfront.net"
if [[ -n "${PUBLIC_ORIGIN_CLEAN}" && "${PUBLIC_ORIGIN_CLEAN}" != "http://localhost" ]]; then
  CORS_LIST="${CORS_LIST},${PUBLIC_ORIGIN_CLEAN}"
fi
if [[ -n "${EC2_PUBLIC_IP}" ]]; then
  CORS_LIST="${CORS_LIST},http://${EC2_PUBLIC_IP},http://${EC2_PUBLIC_IP}:8080"
fi

cat <<EOF > "${ENV_FILE}"
# Generated by configure-lab.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
SPRING_PROFILES_ACTIVE=${SPRING_PROFILE}
JDK_JAVA_OPTIONS=-Xms64m -Xmx192m -XX:+UseSerialGC -Xss512k

# Database (Docker Postgres or Amazon RDS)
DB_HOST=${DB_HOST_VAL}
DB_PORT=${DB_PORT_VAL}
DB_NAME=${DB_NAME_VAL}
DB_USERNAME=${DB_USER_VAL}
DB_PASSWORD=${DB_PASS_VAL}

# RabbitMQ Broker
RABBITMQ_USER=guest
RABBITMQ_PASS=guest

# SMTP Email Service
MAIL_HOST=smtp.gmail.com
MAIL_PORT=587
MAIL_USERNAME=${MAIL_USER_VAL}
MAIL_PASSWORD=${MAIL_PASS_VAL}

# Microsoft Entra ID (Backend validation)
JWT_ISSUER=https://login.microsoftonline.com/e5372bf0-c5e3-4286-887c-79069f209c1f/v2.0
JWT_AUDIENCE=api://4c9cb95d-2a2e-4f3c-88eb-1fbe551829b5,4c9cb95d-2a2e-4f3c-88eb-1fbe551829b5

# AWS Cognito User Pool (Injected into backend & frontend runtime-config.json)
COGNITO_REGION=${COGNITO_REGION_VAL}
COGNITO_USER_POOL_ID=${COGNITO_POOL_VAL}
COGNITO_ISSUER=${COGNITO_ISSUER_VAL}
COGNITO_CLIENT_ID=${COGNITO_CLIENT_VAL}
COGNITO_DOMAIN=${COGNITO_DOMAIN_VAL}
COGNITO_REDIRECT_URI=${COGNITO_REDIRECT_VAL}
COGNITO_SCOPES=openid profile email

# CORS Allowed Origins
CORS_ALLOWED_ORIGINS=${CORS_LIST}
EOF

echo ""
echo "[OK] Archivo ${ENV_FILE} generado correctamente."
echo "     Para aplicar la configuración sin recompilar imágenes:"
echo "     docker compose up -d"
